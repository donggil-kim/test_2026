ATTACK_COUNT_ALL = {"T1200", "T1052", "T1052.001", "T1669", "T1195.003", "T1091"}
ATTACK_COUNT_KEYWORD = {"T1585", "T1585.001", "T1593.001", "T1591.001", "T1591.004", "T1589.003", "T1598"}
ATTACK_HUMAN_KEYWORDS = re.compile(
    r"LinkedIn|job (?:offer|vacanc|posting|board)|hiring|recruit|\bHR\b|interview|persona|fake (?:profile|social)|"
    r"fictitious|professional networking|employee|staff|executives|individuals|team structure|physical location",
    re.I)


def attack_counts(tid, text):
    """True면 이 절차를 물리·인적 맥락 사례로 센다"""
    if tid in ATTACK_COUNT_ALL:
        return True
    if tid in ATTACK_COUNT_KEYWORD:
        return bool(ATTACK_HUMAN_KEYWORDS.search(text))
    return False


